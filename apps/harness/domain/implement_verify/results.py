"""Closed set of Implement and Verify results and rejection reasons (feature-t4 design §结果码闭集).

Separate from the acceptance closed set (domain/acceptance/results.py) and the Workflow closed set
(domain/workflow/results.py): the three never cover each other, and a Workflow rejection raised by
feature-t2 while this package drives it is passed through unchanged. Every non-success result carries
a machine-readable reason object and a human-readable message.
"""

DISPATCHED = "DISPATCHED"
IMPLEMENT_COMPLETED = "IMPLEMENT_COMPLETED"
CANDIDATE_ROUTED = "CANDIDATE_ROUTED"
VERIFY_NOT_APPLICABLE = "VERIFY_NOT_APPLICABLE"
VERIFY_PASS = "VERIFY_PASS"
VERIFY_FAIL = "VERIFY_FAIL"
CHECKS_CONFIGURED = "CHECKS_CONFIGURED"
REGISTRATION_CONFIGURED = "REGISTRATION_CONFIGURED"
REMEDIATION_ROUTED = "REMEDIATION_ROUTED"
ASSESSED = "ASSESSED"
SETTLED = "SETTLED"
PENDING = "PENDING"
IDEMPOTENT_REPLAY = "IDEMPOTENT_REPLAY"

WORKTREE_BINDING_MISMATCH = "WORKTREE_BINDING_MISMATCH"
ACCEPTANCE_REQUIRED = "ACCEPTANCE_REQUIRED"
CAPACITY_EXHAUSTED = "CAPACITY_EXHAUSTED"
ROLE_NOT_LEGAL_HERE = "ROLE_NOT_LEGAL_HERE"
AUTHORITY_NOT_DERIVABLE = "AUTHORITY_NOT_DERIVABLE"
EXECUTION_WRITER_BUSY = "EXECUTION_WRITER_BUSY"
PROFILE_PURPOSE_MISMATCH = "PROFILE_PURPOSE_MISMATCH"
BUDGET_EXCEEDS_PROFILE = "BUDGET_EXCEEDS_PROFILE"
IDENTITY_UNVERIFIED = "IDENTITY_UNVERIFIED"
VENDOR_MAPPING_UNKNOWN = "VENDOR_MAPPING_UNKNOWN"
APPROVAL_OUT_OF_POLICY = "APPROVAL_OUT_OF_POLICY"
CANDIDATE_MISMATCH = "CANDIDATE_MISMATCH"
VERIFICATION_RESULT_IMMUTABLE = "VERIFICATION_RESULT_IMMUTABLE"
BUDGET_DECISION_MISSING = "BUDGET_DECISION_MISSING"
RESERVATION_HELD = "RESERVATION_HELD"
REGISTRY_ENTRY_MISSING = "REGISTRY_ENTRY_MISSING"
REGISTRATION_INVALID = "REGISTRATION_INVALID"
CHECKS_INVALID = "CHECKS_INVALID"
AUTHORIZATION_CALLBACK_DENIED = "AUTHORIZATION_CALLBACK_DENIED"
REQUEST_CONFLICT = "REQUEST_CONFLICT"
POSITION_NOT_APPLICABLE = "POSITION_NOT_APPLICABLE"

STOP_UNCONFIRMED = "STOP_UNCONFIRMED"
RESULT_UNKNOWN = "RESULT_UNKNOWN"
CHECK_EXECUTION_FAILED = "CHECK_EXECUTION_FAILED"
PRESCRIBED_CHECK_UNREGISTERED = "PRESCRIBED_CHECK_UNREGISTERED"
INDETERMINATE = "INDETERMINATE"

SUCCESS = (DISPATCHED, IMPLEMENT_COMPLETED, CANDIDATE_ROUTED, VERIFY_NOT_APPLICABLE, VERIFY_PASS, VERIFY_FAIL,
           CHECKS_CONFIGURED, REGISTRATION_CONFIGURED, REMEDIATION_ROUTED, ASSESSED, SETTLED, PENDING,
           IDEMPOTENT_REPLAY)
REJECTIONS = (WORKTREE_BINDING_MISMATCH, ACCEPTANCE_REQUIRED, CAPACITY_EXHAUSTED, ROLE_NOT_LEGAL_HERE,
              AUTHORITY_NOT_DERIVABLE, EXECUTION_WRITER_BUSY, PROFILE_PURPOSE_MISMATCH, BUDGET_EXCEEDS_PROFILE,
              IDENTITY_UNVERIFIED, VENDOR_MAPPING_UNKNOWN, APPROVAL_OUT_OF_POLICY, CANDIDATE_MISMATCH,
              VERIFICATION_RESULT_IMMUTABLE, BUDGET_DECISION_MISSING, RESERVATION_HELD, REGISTRY_ENTRY_MISSING,
              REGISTRATION_INVALID, CHECKS_INVALID, AUTHORIZATION_CALLBACK_DENIED, REQUEST_CONFLICT,
              POSITION_NOT_APPLICABLE)
NOT_DETERMINABLE = (STOP_UNCONFIRMED, RESULT_UNKNOWN, CHECK_EXECUTION_FAILED, PRESCRIBED_CHECK_UNREGISTERED,
                    INDETERMINATE)
RESULTS = SUCCESS + REJECTIONS + NOT_DETERMINABLE


class ImplementVerifyRejection(Exception):
    """A determinate or indeterminate non-progression of the Implement and Verify loop."""

    def __init__(self, code, message, **detail):
        if code not in RESULTS or code in SUCCESS:
            raise ValueError("Unknown implement/verify rejection code: " + str(code))
        self.code, self.detail = code, dict(detail)
        super().__init__(message)

    def reason(self):
        return dict(code=self.code, message=str(self), **self.detail)


def exit_code(code):
    """0 completed, 1 determinate rejection, 2 not determinable (repository tool convention)."""
    if code in SUCCESS:
        return 0
    if code in NOT_DETERMINABLE:
        return 2
    return 1

"""Closed set of Validate Change results (feature-t5 design, 结果码闭集; finalised in construction)."""
VALIDATION_CONFIGURED = "VALIDATION_CONFIGURED"
REVIEW_DISPATCHED = "REVIEW_DISPATCHED"
FORMAL_AUTHORIZATION_RECORDED = "FORMAL_AUTHORIZATION_RECORDED"
VERDICT_RECORDED = "VERDICT_RECORDED"
RULING_REGISTERED = "RULING_REGISTERED"
FINDING_DISPOSED = "FINDING_DISPOSED"
RESERVATION_ACCEPTED = "RESERVATION_ACCEPTED"
REMEDIATION_RESUMED = "REMEDIATION_RESUMED"
EXECUTION_SETTLED = "EXECUTION_SETTLED"
IDEMPOTENT_REPLAY = "IDEMPOTENT_REPLAY"
VALIDATION_READ = "VALIDATION_READ"

POSITION_NOT_APPLICABLE = "POSITION_NOT_APPLICABLE"
CANDIDATE_NOT_VERIFIED = "CANDIDATE_NOT_VERIFIED"
REVIEW_MATERIAL_MISMATCH = "REVIEW_MATERIAL_MISMATCH"
FORMAL_AUTHORIZATION_NOT_APPLICABLE = "FORMAL_AUTHORIZATION_NOT_APPLICABLE"
HUMAN_FINDINGS_PENDING = "HUMAN_FINDINGS_PENDING"
RESERVATION_REQUIRED = "RESERVATION_REQUIRED"
BASIS_NOT_FINAL = "BASIS_NOT_FINAL"
DECISION_REQUIRES_VALIDATION_ENTRY = "DECISION_REQUIRES_VALIDATION_ENTRY"
REQUEST_CONFLICT = "REQUEST_CONFLICT"
INPUT_INVALID = "INPUT_INVALID"
EXECUTION_IN_FLIGHT = "EXECUTION_IN_FLIGHT"

REVIEW_RESULT_UNKNOWN = "REVIEW_RESULT_UNKNOWN"
INDETERMINATE = "INDETERMINATE"

SUCCESS = (VALIDATION_CONFIGURED, REVIEW_DISPATCHED, FORMAL_AUTHORIZATION_RECORDED, VERDICT_RECORDED, RULING_REGISTERED,
           FINDING_DISPOSED, RESERVATION_ACCEPTED, REMEDIATION_RESUMED, EXECUTION_SETTLED, IDEMPOTENT_REPLAY, VALIDATION_READ)
REJECTIONS = (POSITION_NOT_APPLICABLE, CANDIDATE_NOT_VERIFIED, REVIEW_MATERIAL_MISMATCH, FORMAL_AUTHORIZATION_NOT_APPLICABLE,
              HUMAN_FINDINGS_PENDING, RESERVATION_REQUIRED, BASIS_NOT_FINAL, DECISION_REQUIRES_VALIDATION_ENTRY,
              REQUEST_CONFLICT, INPUT_INVALID, EXECUTION_IN_FLIGHT)
NOT_DETERMINABLE = (REVIEW_RESULT_UNKNOWN, INDETERMINATE)
RESULTS = SUCCESS + REJECTIONS + NOT_DETERMINABLE
# Results that settle a Runtime Operation as succeeded.
OPERATION_SUCCEEDED = (VALIDATION_CONFIGURED, REVIEW_DISPATCHED, FORMAL_AUTHORIZATION_RECORDED, VERDICT_RECORDED,
                       FINDING_DISPOSED, RESERVATION_ACCEPTED, REMEDIATION_RESUMED, IDEMPOTENT_REPLAY)


class ValidationRejection(Exception):
    """A determinate or indeterminate refusal of a Validate Change command; nothing is recorded."""

    def __init__(self, code, message, **detail):
        if code not in RESULTS or code in SUCCESS:
            raise ValueError("Unknown validate-change rejection code: " + str(code))
        self.code, self.detail = code, dict(detail)
        super().__init__(message)

    def reason(self):
        return dict(code=self.code, message=str(self), **self.detail)


def exit_code(code):
    if code in SUCCESS:
        return 0
    if code in NOT_DETERMINABLE:
        return 2
    return 1

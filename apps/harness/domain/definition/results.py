EXECUTION_LAYER_UNAVAILABLE = "EXECUTION_LAYER_UNAVAILABLE"
REQUEST_CONFLICT = "REQUEST_CONFLICT"
INPUT_INVALID = "INPUT_INVALID"

SUCCESS = (CANDIDATE_RECORDED, REVIEW_ROUTED, REVIEW_DISPATCHED, VERDICT_RECORDED, RULING_WRITTEN, RULING_REGISTERED,
           DEFINITION_FROZEN, FORMAL_AUTHORIZATION_RECORDED, FINDING_DISPOSED, EXECUTION_SETTLED, IDEMPOTENT_REPLAY)
NOT_DETERMINABLE = (TEMPLATE_VALIDATOR_UNAVAILABLE, RULING_WRITE_INDETERMINATE, EXECUTION_RESULT_UNKNOWN,
                    EXECUTION_LAYER_UNAVAILABLE, AUTHORIZER_UNAVAILABLE, EXECUTION_BINDING_UNAVAILABLE)
REJECTIONS = (
    CANDIDATE_NOT_IN_COMMIT, CANDIDATE_NOT_ON_TASK_BRANCH, TEMPLATE_STRUCTURE_INVALID, TEMPLATE_VALIDATOR_UNAVAILABLE,
    IDENTITY_MISMATCH, SOURCE_ANCHOR_MISMATCH, AUTHOR_EVIDENCE_UNREADABLE, REVISION_NOT_ALLOWED_HERE,
    POSITION_NOT_APPLICABLE, PORT_NOT_REGISTERED, PORT_ENTRY_MISMATCH, FORMAL_AUTHORIZATION_NOT_APPLICABLE,
    AUTHORIZER_UNAVAILABLE, AUTHORIZATION_REFUSED, EXECUTION_BINDING_UNAVAILABLE, REVIEW_MATERIAL_MISMATCH,
    VERDICT_NOT_ACCEPTABLE, HUMAN_FINDINGS_PENDING, BASIS_MISSING, BASIS_NOT_FINAL, CANDIDATE_BYTES_CHANGED,
    RESERVATION_REQUIRED, DECISION_REQUIRES_DEFINITION_ENTRY, RULING_WRITE_PRECONDITION_FAILED,
    RULING_WRITE_INDETERMINATE, EXECUTION_RESULT_UNKNOWN, EXECUTION_LAYER_UNAVAILABLE, REQUEST_CONFLICT, INPUT_INVALID)
RESULTS = SUCCESS + REJECTIONS


class DefinitionRejection(Exception):
    """A determinate or indeterminate Definition-loop refusal with a machine-readable reason object."""

    def __init__(self, code, message, **detail):
        if code not in REJECTIONS:
            raise ValueError("Unknown definition rejection code: " + str(code))
        self.code, self.detail = code, dict(detail)
        super().__init__(message)

    def reason(self):
        return dict(code=self.code, message=str(self), **self.detail)


def exit_code(code):
    """0 completed, 1 determinate rejection, 2 not determinable (repository tool convention)."""
    if code in SUCCESS:
        return 0
    if code in NOT_DETERMINABLE:
        return 2
    return 1

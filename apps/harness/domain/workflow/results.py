"""Closed set of Workflow progression results and rejection reasons (feature-t2 design §结果码闭集).

Separate from the acceptance closed set in domain/acceptance/results.py: the two never cover each
other. Every non-success result carries a machine-readable reason object and a human-readable
message; adding a reason means changing the design and adding a positive and a negative test.
"""
ADVANCED = "ADVANCED"
CONDITION_UPDATED = "CONDITION_UPDATED"
FINALIZED = "FINALIZED"
IDEMPOTENT_REPLAY = "IDEMPOTENT_REPLAY"

REQUEST_CONFLICT = "REQUEST_CONFLICT"
VERSION_CONFLICT = "VERSION_CONFLICT"
STALE_CONTROL_GENERATION = "STALE_CONTROL_GENERATION"
EXTERNAL_DRIFT = "EXTERNAL_DRIFT"
ILLEGAL_STATE_COMBINATION = "ILLEGAL_STATE_COMBINATION"
ILLEGAL_TRANSITION = "ILLEGAL_TRANSITION"
TRIGGER_NOT_APPLICABLE = "TRIGGER_NOT_APPLICABLE"
TRIGGER_ALREADY_CONSUMED = "TRIGGER_ALREADY_CONSUMED"
AUTHORITY_MISSING = "AUTHORITY_MISSING"
DECISION_NOT_LEGAL_HERE = "DECISION_NOT_LEGAL_HERE"
TASK_TERMINAL = "TASK_TERMINAL"
PUBLISHED_NOT_CLOSEABLE = "PUBLISHED_NOT_CLOSEABLE"
RECOVERY_REQUIRED_BLOCKS_PROGRESSION = "RECOVERY_REQUIRED_BLOCKS_PROGRESSION"
ASSESSMENT_STALE = "ASSESSMENT_STALE"
ASSESSMENT_ALREADY_CONSUMED = "ASSESSMENT_ALREADY_CONSUMED"
RECOVERY_AUTHORIZATION_MISSING = "RECOVERY_AUTHORIZATION_MISSING"
RESERVATION_HELD = "RESERVATION_HELD"
TASK_NOT_FOUND = "TASK_NOT_FOUND"
TOPOLOGY_UNREADABLE = "TOPOLOGY_UNREADABLE"
INDETERMINATE = "INDETERMINATE"
LOCK_UNAVAILABLE = "LOCK_UNAVAILABLE"
STORE_UNAVAILABLE = "STORE_UNAVAILABLE"

SUCCESS = (ADVANCED, CONDITION_UPDATED, FINALIZED, IDEMPOTENT_REPLAY)
NOT_DETERMINABLE = (INDETERMINATE, EXTERNAL_DRIFT, LOCK_UNAVAILABLE, STORE_UNAVAILABLE, TOPOLOGY_UNREADABLE)
RESULTS = SUCCESS + (
    REQUEST_CONFLICT, VERSION_CONFLICT, STALE_CONTROL_GENERATION, EXTERNAL_DRIFT, ILLEGAL_STATE_COMBINATION,
    ILLEGAL_TRANSITION, TRIGGER_NOT_APPLICABLE, TRIGGER_ALREADY_CONSUMED, AUTHORITY_MISSING,
    DECISION_NOT_LEGAL_HERE, TASK_TERMINAL, PUBLISHED_NOT_CLOSEABLE, RECOVERY_REQUIRED_BLOCKS_PROGRESSION,
    ASSESSMENT_STALE, ASSESSMENT_ALREADY_CONSUMED, RECOVERY_AUTHORIZATION_MISSING, RESERVATION_HELD,
    TASK_NOT_FOUND, TOPOLOGY_UNREADABLE, INDETERMINATE, LOCK_UNAVAILABLE, STORE_UNAVAILABLE)


class WorkflowRejection(Exception):
    """A determinate or indeterminate non-progression carrying a machine-readable reason object."""

    def __init__(self, code, message, **detail):
        if code not in RESULTS or code in SUCCESS:
            raise ValueError("Unknown workflow rejection code: " + str(code))
        self.code, self.detail = code, dict(detail)
        super().__init__(message)

    def reason(self):
        return dict(code=self.code, message=str(self), **self.detail)


def exit_code(code):
    """0 completed, 1 determinate rejection, 2 not determinable (repository tool convention)."""
    if code in SUCCESS:
        return 0
    if code in NOT_DETERMINABLE:
        return 2
    return 1
